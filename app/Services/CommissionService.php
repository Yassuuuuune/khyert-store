<?php

namespace App\Services;

use App\Models\Commission;
use App\Models\Order;
use App\Models\User;
use Illuminate\Support\Facades\DB;

/**
 * Owns the affiliate commission ledger.
 *
 * Ledger lifecycle:  pending  →  approved  →  paid
 *                              ↘ cancelled
 *
 * Commissions are only *approved* once the order reaches the status configured
 * in `config('affiliate.commission_trigger_status')` (default: delivered).
 * Cancelled or refunded orders always invalidate their commissions.
 *
 * These records are system-owned: no affiliate-facing endpoint is allowed to
 * create, edit or delete a commission row.
 */
class CommissionService
{
    /**
     * Approve every pending commission attached to an order.
     */
    public function approveForOrder(Order $order): int
    {
        $commissions = $order->commissions()->where('status', 'pending')->get();

        if ($commissions->isEmpty()) {
            return 0;
        }

        DB::transaction(function () use ($commissions) {
            foreach ($commissions as $commission) {
                $commission->update([
                    'status'      => 'approved',
                    'approved_at' => now(),
                ]);

                $this->refreshProfile($commission->affiliate);
            }
        });

        return $commissions->count();
    }

    /**
     * Cancel every non-paid commission attached to an order.
     * Commissions already paid out are left untouched (money has moved).
     */
    public function cancelForOrder(Order $order, ?string $reason = null): int
    {
        $commissions = $order->commissions()
            ->whereIn('status', ['pending', 'approved'])
            ->get();

        if ($commissions->isEmpty()) {
            return 0;
        }

        DB::transaction(function () use ($commissions, $reason) {
            foreach ($commissions as $commission) {
                $commission->update([
                    'status' => 'cancelled',
                    'notes'  => $reason ?: $commission->notes,
                ]);

                $commission->orderItem?->update(['commission_generated' => false]);

                $this->refreshProfile($commission->affiliate);
            }
        });

        return $commissions->count();
    }

    /**
     * Mark the given commissions as paid and refresh the affiliate totals.
     *
     * @param  iterable<int, Commission>  $commissions
     */
    public function markPaid(iterable $commissions): void
    {
        DB::transaction(function () use ($commissions) {
            foreach ($commissions as $commission) {
                $commission->update([
                    'status'  => 'paid',
                    'paid_at' => now(),
                ]);

                $this->refreshProfile($commission->affiliate);
            }
        });
    }

    /**
     * Recompute an affiliate's cached counters from the ledger.
     *
     * This is the single place where affiliate_profiles money columns are
     * written, which keeps the dashboard numbers consistent with the ledger.
     */
    public function refreshProfile(?User $affiliate): void
    {
        if (! $affiliate) {
            return;
        }

        $profile = $affiliate->affiliateProfile;

        if (! $profile) {
            return;
        }

        $totals = Commission::where('affiliate_id', $affiliate->id)
            ->selectRaw("
                COALESCE(SUM(CASE WHEN status IN ('pending','approved','paid') THEN commission_amount ELSE 0 END), 0) AS earned,
                COALESCE(SUM(CASE WHEN status = 'pending'  THEN commission_amount ELSE 0 END), 0) AS pending,
                COALESCE(SUM(CASE WHEN status = 'approved' THEN commission_amount ELSE 0 END), 0) AS approved,
                COALESCE(SUM(CASE WHEN status = 'paid'     THEN commission_amount ELSE 0 END), 0) AS paid
            ")
            ->first();

        $pendingTotal = (float) ($totals->pending ?? 0) + (float) ($totals->approved ?? 0);

        $profile->update([
            'total_earned'  => (float) ($totals->earned ?? 0),
            'total_pending' => $pendingTotal,
            'total_paid'    => (float) ($totals->paid ?? 0),
            'balance'       => $pendingTotal,
        ]);
    }

    /**
     * Number of conversions (distinct paid orders) generated by an affiliate.
     */
    public function conversions(User $affiliate): int
    {
        return Commission::where('affiliate_id', $affiliate->id)
            ->distinct('order_id')
            ->count('order_id');
    }
}
